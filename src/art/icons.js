function button(letter, col, dk) {
  const p = new Pix(16, 16);
  p.ellipse(8, 8, 7.5, 7.5, P.ink);
  p.ellipse(8, 8, 6.5, 6.5, dk);
  p.ellipse(7.5, 7.5, 5.8, 5.8, col);
  p.set(4, 4, P.white); p.set(5, 3, P.white);
  const glyph = letter === 'A' ? ['.ww.', 'w..w', 'wwww', 'w..w', 'w..w'] : ['www.', 'w..w', 'www.', 'w..w', 'www.'];
  glyph.forEach((r, y) => [...r].forEach((ch, x) => { if (ch === 'w') { p.set(6 + x, 6 + y, P.white); p.set(7 + x, 7 + y, p.get(7 + x, 7 + y) === mat('w', { w: P.white }).d[0] ? P.white : dk); } }));
  // redraw glyph on top (shadow pass may have overwritten)
  glyph.forEach((r, y) => [...r].forEach((ch, x) => { if (ch === 'w') p.set(6 + x, 6 + y, P.white); }));
  return p.canvas();
}

export function buildIcons() {
  const I = { ...hearts() };
  for (const [k, s] of Object.entries(ICONS)) I[k] = mat(s, L).canvas();
  I.button_a = button('A', P.red_md, P.red_dk);
  I.button_b = button('B', P.gold_md, P.gold_dk);
  return I;
}
