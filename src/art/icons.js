function hearts() {
  const full = mat(HEART, { o: P.ink, i: P.heart_hi, M: P.heart_md, d: P.heart_dk }, 8, 8);
  const empty = mat(HEART, { o: P.ink, i: P.night, M: P.night, d: P.night }, 8, 8);
  empty.d = empty.d.map((v, i) => v); // keep
  // empty: heart_dk inner rim, night fill
  const e = empty.clone();
  for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) {
    if (full.get(x, y) && full.get(x, y) !== mat('o', { o: P.ink }).d[0]) {
      const edge = [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => full.get(x + dx, y + dy) === mat('o', { o: P.ink }).d[0]);
      e.put(x, y, edge ? P.heart_dk : P.night);
    }
  }
  const half = e.clone();
  for (let y = 0; y < 8; y++) for (let x = 0; x < 4; x++) if (full.get(x, y)) half.put(x, y, full.get(x, y));
  return { heart_full: full.canvas(), heart_half: half.canvas(), heart_empty: e.canvas() };
}
