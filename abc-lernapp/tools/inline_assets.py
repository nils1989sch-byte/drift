#!/usr/bin/env python3
"""Inline the design assets (design/*.svg) into app.html.

Replaces everything between <!--ASSETS:BEGIN--> and <!--ASSETS:END--> in app.html with
  1. one zero-size <svg> that holds ALL <defs>, <clipPath>s and <mask>s of every asset
     (ids are pre-namespaced per file; duplicates are dropped). Living in one visible,
     never-hidden place keeps url(#…) references working even when the copy of an asset
     that appears first in the document sits inside a display:none screen (Safari/Firefox).
  2. a <script> defining `ART` = {ill:{A:'<svg…>',…}, bruno:'…', sc:{cloud:'…',…}} with the
     defs stripped, so every copy rendered by the app is small.
Run:  python3 tools/inline_assets.py   (then ./build.sh)
"""
import json, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
D = ROOT / 'design'
defs, seen = [], set()

def take_defs(svg):
    def grab(block):
        for m in re.finditer(r'<(radialGradient|linearGradient|filter|clipPath|mask|pattern)\b[^>]*\bid="([^"]+)"[^>]*>.*?</\1>', block, re.S):
            if m.group(2) not in seen:
                seen.add(m.group(2)); defs.append(m.group(0))
    for m in re.finditer(r'<defs>(.*?)</defs>', svg, re.S): grab(m.group(1))
    svg = re.sub(r'<defs>.*?</defs>|<defs/>', '', svg, flags=re.S)
    for m in re.finditer(r'<(clipPath|mask)\b[^>]*>.*?</\1>', svg, re.S): grab(m.group(0))
    svg = re.sub(r'<(clipPath|mask)\b[^>]*>.*?</\1>', '', svg, flags=re.S)
    svg = svg.replace(' xmlns="http://www.w3.org/2000/svg"', '')
    return svg.strip()

art = {'ill': {}, 'sc': {}}
words = json.loads((D / 'words.json').read_text())
for w in words:
    art['ill'][w['letter']] = take_defs((D / w['file']).read_text())
b = (D / 'bruno.svg').read_text()
b = re.sub(r'<style>.*?</style>', '', b, flags=re.S)       # moods/idle CSS lives in app.html
b = take_defs(b)
b = re.sub(r'\sid="[^"]+"', '', b)                          # Bruno appears several times: classes only
b = b.replace('class="bruno alive"', 'class="bruno"')
art['bruno'] = b
for f in sorted((D / 'scenery').glob('*.svg')):
    art['sc'][f.stem] = take_defs(f.read_text())

block = ('<!--ASSETS:BEGIN (generated by tools/inline_assets.py from design/ – do not edit by hand)-->\n'
         '<svg class="defs-sprite" aria-hidden="true" focusable="false" width="0" height="0" '
         'style="position:absolute;width:0;height:0;overflow:hidden"><defs>' + ''.join(defs) + '</defs></svg>\n'
         '<script>const WORDS=' + json.dumps([[w['letter'], w['word']] for w in words], ensure_ascii=False) +
         ';\nconst ART=' + json.dumps(art, ensure_ascii=False, separators=(',', ':')) + ';</script>\n<!--ASSETS:END-->')
app = ROOT / 'app.html'
s = app.read_text()
s2, n = re.subn(r'<!--ASSETS:BEGIN.*?<!--ASSETS:END-->', lambda m: block, s, flags=re.S)
if n != 1: raise SystemExit('ASSETS markers not found in app.html')
app.write_text(s2)
print(f'inlined {len(words)} illustrations, {len(art["sc"])} scenery, bruno; {len(defs)} defs; block {len(block)//1024} KB')
